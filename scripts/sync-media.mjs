import { execFileSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import ffmpegPath from 'ffmpeg-static';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const mediaDir = process.env.MEDIA_DIR ?? join(root, '..', '..', 'media');
const publicGallery = join(root, 'public', 'gallery');
const publicVideos = join(root, 'public', 'videos');
const publicVideosWeb = join(publicVideos, 'web');
const generatedDir = join(root, 'src', 'generated');

const videoSlotFiles = [
  { id: 'v1', file: 'moment-1.mp4' },
  { id: 'v2', file: 'moment-2.mp4' },
  { id: 'v3', file: 'moment-3.mp4' },
];

const IMAGE_RE = /\.(jpe?g|png|gif|webp)$/i;
const PLACEHOLDER_RE = /^gallery-\d+\.(jpe?g|png)$/i;

mkdirSync(publicGallery, { recursive: true });
mkdirSync(publicVideos, { recursive: true });
mkdirSync(publicVideosWeb, { recursive: true });
mkdirSync(generatedDir, { recursive: true });

function galleryPublicSrc(file) {
  return `/gallery/${encodeURIComponent(file)}`;
}

function altFromFilename(file) {
  const base = file.replace(/\.[^.]+$/, '').replace(/[_-]+/g, ' ');
  return `Ruu — ${base}`;
}

function categoryFromFilename(file) {
  if (/\.png$/i.test(file)) return 'craft';
  if (/IMG_00(68|69|70|71|72)/i.test(file)) return 'together';
  return 'candid';
}

function listPublicGalleryImages() {
  return readdirSync(publicGallery)
    .filter((f) => IMAGE_RE.test(f) && !PLACEHOLDER_RE.test(f))
    .sort((a, b) => a.localeCompare(b, undefined, { numeric: true, sensitivity: 'base' }));
}

function isTinyPlaceholder(file) {
  if (!PLACEHOLDER_RE.test(file)) return false;
  try {
    return statSync(join(publicGallery, file)).size < 2048;
  } catch {
    return true;
  }
}

function writeGalleryItems() {
  let files = listPublicGalleryImages();
  if (files.length === 0) {
    files = readdirSync(publicGallery)
      .filter((f) => IMAGE_RE.test(f) && PLACEHOLDER_RE.test(f) && !isTinyPlaceholder(f))
      .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));
  }
  if (files.length === 0) {
    files = readdirSync(publicGallery)
      .filter((f) => IMAGE_RE.test(f) && PLACEHOLDER_RE.test(f))
      .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));
  }

  const items = files.map((file, i) => {
    const id = String(i + 1).padStart(2, '0');
    const category = categoryFromFilename(file);
    return {
      id,
      src: galleryPublicSrc(file),
      category,
      alt: altFromFilename(file),
    };
  });

  const lines = items.map(
    (item) =>
      `  { id: '${item.id}', src: '${item.src}', category: '${item.category}', alt: '${item.alt.replace(/'/g, "\\'")}' },`,
  );

  writeFileSync(
    join(generatedDir, 'galleryItems.ts'),
    `// Auto-generated by sync-media from public/gallery/. Do not edit.\nimport type { GalleryItem } from '../data/gallery';\n\nexport const galleryItems: GalleryItem[] = [\n${lines.join('\n')}\n];\n`,
  );

  console.log(`Indexed ${items.length} image(s) from public/gallery/ → src/generated/galleryItems.ts`);
  return items;
}

const VIDEO_RE = /\.(mp4|mov|webm)$/i;

function mimeForVideo(file) {
  if (/\.webm$/i.test(file)) return 'video/webm';
  if (/\.mov$/i.test(file)) return 'video/quicktime';
  return 'video/mp4';
}

function listSourceVideos() {
  if (!existsSync(publicVideos)) return [];
  return readdirSync(publicVideos)
    .filter((f) => VIDEO_RE.test(f) && f !== 'web')
    .sort((a, b) => {
      const aPhone = /^IMG_/i.test(a);
      const bPhone = /^IMG_/i.test(b);
      if (aPhone && !bPhone) return -1;
      if (!aPhone && bPhone) return 1;
      return a.localeCompare(b, undefined, { numeric: true, sensitivity: 'base' });
    });
}

/** One web file per source basename — slot index used to change breaks stale ruu-NN.mp4 caches. */
function webOutNameForSource(sourceFile) {
  const base = sourceFile.replace(/\.[^.]+$/i, '');
  const safe = base.replace(/[^a-zA-Z0-9._-]+/g, '-').slice(0, 120);
  return `${safe}.mp4`;
}

/** Browsers need H.264 MP4 — iPhone .MOV often won't play inline in Chrome. */
function ensureWebMp4(sourceFile) {
  const inputPath = join(publicVideos, sourceFile);
  const outName = webOutNameForSource(sourceFile);
  const outputPath = join(publicVideosWeb, outName);

  if (/\.mp4$/i.test(sourceFile)) {
    try {
      const srcMtime = statSync(inputPath).mtimeMs;
      if (existsSync(outputPath) && statSync(outputPath).mtimeMs >= srcMtime) {
        return { outName, original: sourceFile };
      }
      if (!ffmpegPath) {
        cpSync(inputPath, outputPath, { force: true });
        return { outName, original: sourceFile };
      }
      console.log(`Optimizing ${sourceFile} → web/${outName}…`);
      execFileSync(
        ffmpegPath,
        [
          '-y',
          '-i',
          inputPath,
          '-c:v',
          'libx264',
          '-crf',
          '23',
          '-preset',
          'fast',
          '-c:a',
          'aac',
          '-b:a',
          '128k',
          '-movflags',
          '+faststart',
          '-pix_fmt',
          'yuv420p',
          outputPath,
        ],
        { stdio: 'inherit' },
      );
      return { outName, original: sourceFile };
    } catch {
      return null;
    }
  }

  if (!ffmpegPath) {
    console.warn('ffmpeg-static missing — videos may not play in Chrome. Install or add .mp4 files.');
    return null;
  }

  try {
    const srcMtime = statSync(inputPath).mtimeMs;
    if (existsSync(outputPath) && statSync(outputPath).mtimeMs >= srcMtime) {
      return { outName, original: sourceFile };
    }
    console.log(`Transcoding ${sourceFile} → web/${outName} (can take a minute)…`);
    execFileSync(
      ffmpegPath,
      [
        '-y',
        '-i',
        inputPath,
        '-c:v',
        'libx264',
        '-crf',
        '23',
        '-preset',
        'fast',
        '-c:a',
        'aac',
        '-b:a',
        '128k',
        '-movflags',
        '+faststart',
        '-pix_fmt',
        'yuv420p',
        outputPath,
      ],
      { stdio: 'inherit' },
    );
    return { outName, original: sourceFile };
  } catch (err) {
    console.warn(`Transcode failed for ${sourceFile}:`, err.message ?? err);
    return null;
  }
}

function writeVideoSrcMap() {
  const videoSrcBySlotId = {};
  for (const { id, file } of videoSlotFiles) {
    if (existsSync(join(publicVideos, file))) {
      videoSrcBySlotId[id] = `/videos/${encodeURIComponent(file)}`;
    }
  }

  const sources = listSourceVideos();
  const clips = [];

  for (let i = 0; i < sources.length; i++) {
    const file = sources[i];
    const web = ensureWebMp4(file);
    const id = String(i + 1).padStart(2, '0');
    const playback = web
      ? `/videos/web/${web.outName}`
      : `/videos/${encodeURIComponent(file)}`;
    clips.push({
      id,
      src: playback,
      mime: web ? 'video/mp4' : mimeForVideo(file),
      label: `Moment ${i + 1}`,
      fallbackSrc: `/videos/${encodeURIComponent(file)}`,
      file,
    });
  }

  if (!videoSrcBySlotId.v1 && clips[0]) {
    videoSrcBySlotId.v1 = clips[0].src;
  }
  if (!videoSrcBySlotId.v2 && clips[1]) {
    videoSrcBySlotId.v2 = clips[1].src;
  }

  writeFileSync(
    join(generatedDir, 'videoSrc.ts'),
    `// Auto-generated by sync-media. Do not edit.\nexport const videoSrcBySlotId: Record<string, string> = ${JSON.stringify(videoSrcBySlotId, null, 2)};\n`,
  );

  const clipLines = clips.map(
    (c) =>
      `  { id: '${c.id}', src: '${c.src}', mime: '${c.mime}', label: '${c.label.replace(/'/g, "\\'")}', fallbackSrc: '${c.fallbackSrc}' },`,
  );
  writeFileSync(
    join(generatedDir, 'videoClips.ts'),
    `// Auto-generated by sync-media from public/videos/. Do not edit.\nexport type VideoClip = { id: string; src: string; mime: string; label: string; fallbackSrc?: string };\n\nexport const videoClips: VideoClip[] = [\n${clipLines.join('\n')}\n];\n`,
  );

  if (clips.length > 0) {
    console.log(`Indexed ${clips.length} video(s) from public/videos/ → src/generated/videoClips.ts`);
  }
}

const publicUserImages = listPublicGalleryImages();

if (!existsSync(mediaDir)) {
  console.warn(`Media folder missing: ${mediaDir}`);
} else {
  const files = readdirSync(mediaDir).filter((f) => /^gallery-\d+\.(jpe?g|png)$/i.test(f));
  if (publicUserImages.length > 0) {
    console.log(
      `Keeping ${publicUserImages.length} image(s) in public/gallery/ (not overwriting with media/ placeholders).`,
    );
  } else if (files.length === 0) {
    console.warn('No gallery-* images in media/. Add photos to public/gallery/ or media/.');
  } else {
    for (const file of files) {
      cpSync(join(mediaDir, file), join(publicGallery, file), { force: true });
    }
    console.log(`Synced ${files.length} image(s) → public/gallery/`);
  }

  const videos = readdirSync(mediaDir).filter((f) => /^moment-\d+\.mp4$/i.test(f));
  for (const file of videos) {
    cpSync(join(mediaDir, file), join(publicVideos, file), { force: true });
  }
  if (videos.length > 0) {
    console.log(`Synced ${videos.length} video(s) → public/videos/`);
  }
}

writeGalleryItems();
writeVideoSrcMap();
